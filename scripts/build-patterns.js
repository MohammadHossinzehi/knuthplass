#!/usr/bin/env node
// Train hyphenation patterns from data/words.txt and write data/patterns.js.
// Also reports held out accuracy: train on 80% of the words, test on the remaining 20%.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { generatePatterns, evaluate } from '../src/patgen.js';
import { Hyphenator } from '../src/hyphenator.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entries = readFileSync(join(root, 'data/words.txt'), 'utf8')
  .split('\n')
  .map((l) => l.trim())
  .filter((l) => l && !l.startsWith('#'));

const pct = (x) => (100 * x).toFixed(1) + '%';
const report = (label, m) =>
  console.log(`${label.padEnd(22)} precision ${pct(m.precision)}  recall ${pct(m.recall)}  (wrong ${m.wrong}, missed ${m.missed})`);

const train = entries.filter((_, i) => i % 5 !== 0);
const test = entries.filter((_, i) => i % 5 === 0);
const split = new Hyphenator(generatePatterns(train).patterns);
report('held out (80/20 split)', evaluate(split, test));

const { patterns, log } = generatePatterns(entries);
const full = new Hyphenator(patterns);
const trainScore = evaluate(full, entries);
report('training set', trainScore);
for (const l of log) console.log(`  level ${l.level} length ${l.length}: +${l.added}`);
console.log(`${patterns.length} patterns from ${entries.length} words`);

const body = patterns.map((p) => JSON.stringify(p)).join(',\n  ');
writeFileSync(
  join(root, 'data/patterns.js'),
  `// Generated by scripts/build-patterns.js from data/words.txt. Do not edit by hand.\n` +
    `// ${patterns.length} patterns; training set precision ${pct(trainScore.precision)}, recall ${pct(trainScore.recall)}.\n` +
    `export const PATTERNS = [\n  ${body},\n];\n`,
);
